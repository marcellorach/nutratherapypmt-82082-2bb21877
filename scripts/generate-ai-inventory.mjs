#!/usr/bin/env node
// Inventário de rotinas (edge functions) que chamam IA.
// Gera src/data/aiInventory.generated.ts — lido pela tela "Governança por tarefa".
// Uso: node scripts/generate-ai-inventory.mjs [--check]
//   --check: falha (exit 1) se o arquivo gerado estiver desatualizado.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const FN_DIR = path.join(ROOT, 'supabase/functions');
const OUT = path.join(ROOT, 'src/data/aiInventory.generated.ts');
const TASKS = path.join(ROOT, 'src/config/ai-tasks.ts');

const PROVIDERS = [
  ['lovable_gateway', /ai\.gateway\.lovable\.dev|LOVABLE_API_KEY|callAITask/],
  ['google_direct', /generativelanguage\.googleapis\.com/],
  ['openai_direct', /api\.openai\.com/],
  ['perplexity', /api\.perplexity\.ai/],
  ['anthropic', /api\.anthropic\.com/],
  ['xai', /api\.x\.ai/],
];
const MODEL_RE = /['"`]((?:google|openai)\/[a-z0-9.\-]+|gemini-[0-9][a-z0-9.\-]*|gpt-[0-9][a-z0-9.\-]*|sonar[a-z0-9.\-]*)['"`]/g;
const READS_SCREEN_RE = /callAITask|resolveTask|ai_model_\$\{|['"]ai_model_[a-z_]+['"]|PDF_MODEL_CONFIG_KEY/;

function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (/\.(ts|js)$/.test(e.name) && !/_test\.ts$|\.test\.ts$/.test(e.name)) out.push(p);
  }
  return out;
}

// task consumers from ai-tasks.ts
const tasksSrc = fs.readFileSync(TASKS, 'utf8');
const taskByFn = new Map();
for (const block of tasksSrc.split(/\n  \{\n/).slice(1)) {
  const id = block.match(/id: "([^"]+)"/)?.[1];
  const cons = block.match(/consumers: \[([^\]]*)\]/)?.[1] ?? '';
  if (!id) continue;
  for (const m of cons.matchAll(/"([a-z0-9\-]+)/g)) {
    const list = taskByFn.get(m[1]) ?? [];
    list.push(id);
    taskByFn.set(m[1], list);
  }
}

// Rotinas de infraestrutura/diagnóstico: usam IA para testar provedores, não executam tarefa de negócio.
const INFRA_FNS = new Set(['ai-task-healthcheck', 'ai-task-test', 'api-keys-manage', 'external-sources-status', 'perplexity-health', 'provider-health', 'test-rag-similarity', 'model-inventory']);

const rows = [];
for (const fn of fs.readdirSync(FN_DIR).sort()) {
  const dir = path.join(FN_DIR, fn);
  if (fn.startsWith('_') || !fs.statSync(dir).isDirectory()) continue;
  const src = walk(dir).map((f) => fs.readFileSync(f, 'utf8')).join('\n');
  const providers = PROVIDERS.filter(([, re]) => re.test(src)).map(([k]) => k);
  if (!providers.length) continue;
  const models = [...new Set([...src.matchAll(MODEL_RE)].map((m) => m[1]))].sort();
  const readsScreen = READS_SCREEN_RE.test(src);
  const tasks = taskByFn.get(fn) ?? [];
  const status = INFRA_FNS.has(fn) ? 'infra' : !tasks.length ? 'unregistered' : readsScreen ? 'obeys_screen' : 'hardcoded';
  rows.push({ fn, providers, status, tasks, hardcoded_models: models });
}

const body = `// AUTO-GENERATED by scripts/generate-ai-inventory.mjs — do not edit by hand.
// Run: node scripts/generate-ai-inventory.mjs

export type AIInventoryStatus = 'obeys_screen' | 'hardcoded' | 'unregistered' | 'infra';
export type AIProvider = ${PROVIDERS.map(([k]) => `'${k}'`).join(' | ')};

export interface AIInventoryRow {
  fn: string;
  providers: AIProvider[];
  status: AIInventoryStatus;
  tasks: string[];
  /** Model ids written literally in the function code (fallbacks included). */
  hardcoded_models: string[];
}

export const AI_INVENTORY: AIInventoryRow[] = ${JSON.stringify(rows, null, 2)};
`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) {
    console.error('[ai-inventory] desatualizado — rode: node scripts/generate-ai-inventory.mjs');
    process.exit(1);
  }
  console.log('[ai-inventory] OK');
} else {
  fs.writeFileSync(OUT, body);
  const c = (s) => rows.filter((r) => r.status === s).length;
  console.log(`[ai-inventory] ${rows.length} rotinas · obedece à tela ${c('obeys_screen')} · fixo no código ${c('hardcoded')} · sem registro ${c('unregistered')} · infraestrutura ${c('infra')}`);
}
